/* Real browser + actual Runtime inference; only disposable Workspace data. */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const base = process.env.WORKSPACE_URL || 'http://127.0.0.1:8892';
  const runtime = process.env.RUNTIME_URL || 'http://127.0.0.1:8885/v1';
  const out = path.resolve(process.env.UI_OUTPUT_DIR || 'tools/out/workspace-chats-ui'); fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: process.env.EDGE_EXE || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  try {
    const models = await (await context.request.get(runtime + '/models')).json();
    const model = models.data.find(m => /qwen3.5/i.test(m.id)).id;
    let boot = await (await context.request.get(base + '/api/bootstrap')).json();
    if (!boot.providers.length) {
      assert.ok((await context.request.post(base + '/api/providers', { data: { base_url: runtime, model } })).ok());
    }
    await page.goto(base);
    await page.getByRole('heading', { name: 'Новый диалог', exact: true }).waitFor();
    await page.getByRole('button', { name: /Runtime подключён/ }).waitFor({ timeout: 20000 });
    assert.ok((await page.locator('.runtime-status').textContent()).includes(new URL(runtime).host));
    assert.equal(await page.getByRole('combobox', { name: 'Проект диалога' }).inputValue(), '');
    assert.equal(await page.locator('.topbar').getByRole('button', { name: /Снимок|копи/ }).count(), 0);
    assert.equal(await page.getByRole('button', { name: '↗ Подключения', exact: true }).count(), 0);
    let avatarCalls = 0, popups = 0;
    context.on('page', () => popups++);
    await page.route('**/api/host/show-avatar', route => { avatarCalls++; return route.fulfill({ json: { ok: true } }); });
    await page.getByRole('button', { name: '◉ Мини-помощник', exact: true }).click();
    assert.equal(avatarCalls, 1); assert.equal(popups, 0, 'Footer must show only avatar, never another window');
    await page.getByRole('textbox', { name: 'Новое сообщение', exact: true }).fill('Remember: my project is named ORBIT. Reply with only OK.');
    await page.getByRole('button', { name: 'Отправить ↗', exact: true }).click();
    await page.locator('.chat-message.assistant:not(.pending)').filter({ hasText: /OK/i }).waitFor({ timeout: 120000 });
    await page.getByRole('textbox', { name: 'Сообщение', exact: true }).fill('What is my project named? Reply with only the name.');
    await page.getByRole('button', { name: 'Отправить ↗', exact: true }).click();
    await page.locator('.chat-message.assistant:not(.pending)').filter({ hasText: 'ORBIT' }).waitFor({ timeout: 120000 });
    boot = await (await context.request.get(base + '/api/bootstrap')).json();
    const chatId = await page.evaluate(() => sessionStorage.getItem('workspace-task'));
    const current = await (await context.request.get(base + '/api/chats/' + chatId)).json();
    assert.equal(current.project_id, null); assert.equal(current.details.mode, 'chat'); assert.equal(current.details.adapter, undefined);
    assert.ok(await page.locator('.chat-message time').first().textContent());
    const bounds = await page.locator('.conversation-messages').boundingBox();
    const userBubble = await page.locator('.chat-message.user').first().boundingBox();
    const modelBubble = await page.locator('.chat-message.assistant:not(.pending)').first().boundingBox();
    assert.ok(userBubble.x + userBubble.width > bounds.x + bounds.width - 50, 'User bubbles align to the right');
    assert.ok(modelBubble.x < bounds.x + 50, 'Model bubbles align to the left');
    await page.screenshot({ path: path.join(out, 'dialog.png'), fullPage: true });
    const scroll = page.locator('.conversation-messages');
    await scroll.evaluate(el => { el.style.flex = 'none'; el.style.height = '100px'; el.scrollTop = 0; el.dispatchEvent(new Event('scroll')); });
    await page.getByRole('textbox', { name: 'Сообщение', exact: true }).fill('What is two plus two? Reply with one word.');
    await page.getByRole('button', { name: 'Отправить ↗', exact: true }).click();
    await page.locator('.chat-message.assistant:not(.pending)').nth(2).waitFor({ timeout: 120000 });
    assert.ok(await scroll.evaluate(el => el.scrollTop) < 5, 'Reply polling must preserve manual scroll');
    await scroll.evaluate(el => { el.style.flex = ''; el.style.height = ''; });
    const before = await page.locator('.task-view').boundingBox();
    await page.getByRole('button', { name: '⚙ Настройки', exact: true }).click();
    await page.getByRole('dialog').waitFor();
    assert.equal(await page.getByRole('link', { name: /Открыть Runtime:/ }).getAttribute('href'), runtime.replace(/\/+$/, '').replace(/\/v1$/, ''));
    assert.deepEqual(await page.locator('.task-view').boundingBox(), before);
    await page.screenshot({ path: path.join(out, 'settings.png'), fullPage: true });
    await page.getByRole('button', { name: 'Проверить связь', exact: true }).click();
    await page.getByText(/Связь установлена/).waitFor();
    await page.getByRole('button', { name: 'Данные', exact: true }).click();
    await page.getByRole('button', { name: 'Создать резервную копию', exact: true }).waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('button', { name: '⚙ Настройки', exact: true }).evaluate(el => el === document.activeElement), true);
    await page.getByRole('button', { name: 'Добавить проект', exact: true }).click();
    await page.getByRole('textbox', { name: 'Название проекта' }).fill('Идеи без репозитория');
    assert.equal(await page.getByRole('textbox', { name: 'Папка проекта', exact: true }).count(), 0);
    await page.screenshot({ path: path.join(out, 'new-project.png'), fullPage: true });
    await page.getByRole('button', { name: 'Создать проект', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'detached' });
    boot = await (await context.request.get(base + '/api/bootstrap')).json();
    assert.ok(boot.projects.some(p => p.name === 'Идеи без репозитория' && p.source === 'virtual'));
    const second = await context.newPage(); popups = 0;
    await second.setViewportSize({ width: 650, height: 500 }); await second.goto(base + '/mini');
    await second.locator('.mini-dialogs button[data-chat-id="' + chatId + '"]').click();
    await second.locator('.chat-message.assistant').filter({ hasText: 'ORBIT' }).waitFor();
    await second.getByRole('textbox', { name: 'Сообщение мини-помощнику' }).fill('  Черновик этого диалога  ');
    await second.getByRole('button', { name: 'Диалоги', exact: true }).click();
    await second.screenshot({ path: path.join(out, 'mini-dialogs.png'), fullPage: true });
    assert.equal(await second.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.setViewportSize({ width: 950, height: 720 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(out, 'result.json'), JSON.stringify({ ok: true, chatId, checks: ['normal chat without project/Git/Harness', 'real ORBIT memory', 'visible Runtime connection and settings link', 'dates', 'manual scroll', 'avatar-only footer', 'unified modal settings', 'backup only in settings', 'project without connection', 'mini dialogue selection', 'compact windows'], errors }, null, 2));
    console.log('Chat-first Workspace browser acceptance passed');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
